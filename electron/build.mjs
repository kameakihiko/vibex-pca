// Bundles main, preload and renderer into dist/. Only @lydell/node-pty stays a runtime dependency:
// it ships native prebuilds per platform, so it cannot be bundled.
// `node build.mjs --gen` only writes the generated icon module (for the type check).
import { build } from 'esbuild';
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';

// Untitled UI icons, the same set and names as macOS Vibex (../scripts/icons.txt). Their licence allows
// using them in the app but not redistributing them, so the generated module stays out of git (.generated/)
// and is rebuilt from the npm package, as ../scripts/fetch-icons.sh does for the Swift app.
function generateIcons() {
  const element = /createElement\("(path|circle|rect|line|polyline|polygon)",\{([^{}]*)\}/g;
  const attribute = /(?:"([\w-]+)"|(\w+)):"([^"]*)"/g;
  const kebab = (s) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());
  const icons = {};
  for (const raw of readFileSync('../scripts/icons.txt', 'utf8').split('\n')) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const [name, source] = line.split(/\s+/);
    const code = readFileSync(`node_modules/@untitledui/icons/dist/${source}.mjs`, 'utf8');
    const shapes = [...code.matchAll(element)].map(([, tag, attrs]) => {
      const pairs = [...attrs.matchAll(attribute)].map(([, q, p, v]) => `${kebab(q ?? p)}="${v}"`).join(' ');
      return `<${tag} ${pairs}/>`;
    });
    if (!shapes.length) throw new Error(`no shapes found in ${source}`);
    icons[name] = shapes.join('');
  }
  mkdirSync('.generated', { recursive: true });
  writeFileSync('.generated/icons.ts', `// Generated by build.mjs from @untitledui/icons. Do not commit (licence: no redistribution).\nexport const ICONS: Record<string, string> = ${JSON.stringify(icons)};\n`);
  return Object.keys(icons).length;
}

const count = generateIcons();
if (process.argv.includes('--gen')) process.exit(0);

// The kind of build (src/main/testSwitches.ts). No flag: dev, for `npm start` and the tests. electron-builder never packs
// that one: its beforePack step (scripts/pack-release.cjs) builds again with --release, or --proof for CI's packaged tests.
const kind = process.argv.includes('--release') ? 'release' : process.argv.includes('--proof') ? 'proof' : 'dev';
const out = process.argv.find((a) => a.startsWith('--out='))?.slice(6) ?? 'dist';
rmSync(out, { recursive: true, force: true });
mkdirSync(`${out}/fonts`, { recursive: true });

// A release has no test code at all, so no environment and no file name can reach it (security review N4, N5). Each call
// becomes a constant here, and esbuild then drops what can never run. A form this does not know stops the build.
const noTestCode = {
  name: 'no-test-code',
  setup(b) {
    b.onLoad({ filter: /[\\/]src[\\/](main|preload|renderer)[\\/][^\\/]+\.ts$/ }, (args) => {
      if (/[\\/]testSwitches\.ts$/.test(args.path)) return undefined;
      const text = readFileSync(args.path, 'utf8')
        .replace(/\btestEnv\('[A-Z0-9_]+'\)/g, 'undefined')
        .replace(/\bisTestRun\(\)/g, 'false')
        .replace(/\(globalThis as any\)\.__vibexTest =/g, 'globalThis.removed =')
        .replace(/\(globalThis as any\)\.__vibexTest/g, 'undefined');
      const code = text.replace(/\/\/.*$/gm, '');
      if (/\btestEnv\(|\bisTestRun\(|__vibexTest/.test(code)) throw new Error(`${args.path}: a test switch in a form the release build cannot remove`);
      return { contents: text, loader: 'ts' };
    });
  },
};

// The site values (src/main/site.ts). Only a release build takes the real ones, from site.local.json or the file that
// VIBEX_PCA_SITE_FILE names; that file is never committed. A dev or proof build keeps the made-up ones, so no test reaches
// a real server. A release with no file is a build for the tests of a pull request: it says so, and it cannot log in anywhere.
function siteValues() {
  if (kind !== 'release') return null;
  const file = process.env.VIBEX_PCA_SITE_FILE || 'site.local.json';
  if (!existsSync(file)) {
    console.warn(`no ${file}: this release build holds the made-up site values of the repository.`);
    return null;
  }
  const read = JSON.parse(readFileSync(file, 'utf8'));
  const site = {};
  for (const name of ['host', 'user', 'hostKey', 'hostKeyFingerprint', 'uploadPage']) {
    if (typeof read[name] !== 'string' || !read[name].trim()) throw new Error(`${file}: "${name}" is missing or empty`);
    site[name] = read[name].trim();
  }
  if (!/^ssh-ed25519 [A-Za-z0-9+/=]+$/.test(site.hostKey)) throw new Error(`${file}: "hostKey" must be "ssh-ed25519 <base64>", with no address and no comment`);
  if (!/^SHA256:[A-Za-z0-9+/]{43}$/.test(site.hostKeyFingerprint)) throw new Error(`${file}: "hostKeyFingerprint" must be "SHA256:" and 43 characters`);
  return site;
}
const site = siteValues();

const common = {
  bundle: true,
  sourcemap: kind !== 'release',
  target: 'es2023',
  logLevel: 'warning',
  banner: { js: `// vibex-build-kind: ${kind}` },
  define: { VIBEX_BUILD_KIND: JSON.stringify(kind), ...(site ? { VIBEX_SITE: JSON.stringify(site) } : {}) },
  ...(kind === 'release' ? { minifySyntax: true, plugins: [noTestCode] } : {}),
};

// dist/main.js is a small first step: ssh runs the app as its askpass helper, and that run needs none of the rest.
await build({
  ...common,
  entryPoints: ['src/main/entry.ts'],
  outfile: `${out}/main.js`,
  platform: 'node',
  format: 'cjs',
  external: ['electron', './app.js'],
});

await build({
  ...common,
  entryPoints: ['src/main/main.ts'],
  outfile: `${out}/app.js`,
  platform: 'node',
  format: 'cjs',
  external: ['electron', '@lydell/node-pty'],
});

await build({
  ...common,
  entryPoints: ['src/preload/preload.ts'],
  outfile: `${out}/preload.js`,
  platform: 'node',
  format: 'cjs',
  external: ['electron'],
});

await build({
  ...common,
  entryPoints: ['src/renderer/renderer.ts'],
  outfile: `${out}/renderer.js`,
  platform: 'browser',
  format: 'iife',
});

copyFileSync('src/renderer/index.html', `${out}/index.html`);
copyFileSync('src/renderer/style.css', `${out}/style.css`);
copyFileSync('node_modules/@xterm/xterm/css/xterm.css', `${out}/xterm.css`);
// Vibex's typefaces (SIL Open Font License, licence files shipped beside them) and its app icon.
for (const font of ['GoogleSans.ttf', 'GoogleSansCode.ttf', 'OFL-GoogleSans.txt', 'OFL-GoogleSansCode.txt']) {
  copyFileSync(`../Vibex/Resources/Fonts/${font}`, `${out}/fonts/${font}`);
}
copyFileSync('../docs/icon.png', `${out}/icon.png`);
console.log(`built ${out}/ (${kind}) with ${count} icons${site ? ', with the site values of this computer' : ''}`);
